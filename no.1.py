kinerja = input ('masukan kinerja mahasiswa : ')

if int(kinerja) >= 90 :
    print('kinerja sangat baik')
elif int(kinerja) >= 80 :
    print('kinerja sangat baik')
elif int(kinerja) >= 70 :
    print('kinerja bagus')
elif int(kinerja) >= 60 :
    print('kinerja rata rata')

else:
    print ('semangat :)' )    

